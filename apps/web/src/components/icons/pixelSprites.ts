/** Names accepted by PixelIcon; state is part of the character name. */
export type PixelIconName = keyof typeof PIXEL_SPRITES;

/** Ordered character names for pickers and sprite registration. */
export const PIXEL_ICON_NAMES = Object.keys(PIXEL_SPRITES) as readonly PixelIconName[];

/**
 * Resolves a character name to its document-local symbol ID.
 * @param name Character name, including dynamic strings from callers.
 * @returns The symbol ID, or undefined for unknown names, matching the design's hidden fallback.
 */
export function getPixelIconSymbolId(name: string): string | undefined {
  return Object.hasOwn(PIXEL_SPRITES, name) ? `px-${name}` : undefined;
}
