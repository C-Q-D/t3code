describe("getLocalEnvironmentBootstraps", () => {
  it.effect("hands out the current window's token to a backend launched with the secret", () =>
    Effect.gen(function* () {
      const result = yield* getLocalEnvironmentBootstraps.handler();

      assert.deepEqual(result, [
        {
          id: "wsl:default",
          label: "WSL (Ubuntu)",
          runningDistro: "Ubuntu",
          httpBaseUrl: "http://127.0.0.1:3774/",
          wsBaseUrl: "ws://127.0.0.1:3774/",
          bootstrapToken: "current-window-token",
        },
      ]);
    }).pipe(
      Effect.provide(
        bootstrapsLayer([
          {
            ...defaultWslInstance,
            currentConfig: Effect.succeedSome({
              ...readyWslConfig,
              bootstrap: {
                ...readyWslConfig.bootstrap,
                desktopBootstrapSecret: "desktop-secret",
              },
            }),
          },
        ]),
      ),
    ),
  );

  it.effect("publishes a pending bootstrap only while a transient retry is scheduled", () => {
    const retryingConfig: DesktopBackendManager.DesktopBackendStartConfig = {
      ...readyWslConfig,
      preflightFailure: Option.some({
        reason: "WSL probe timed out",
        fatal: false,
        retryLimit: 12,
      }),
    };
    const retryingInstance: DesktopBackendManager.DesktopBackendInstance = {
      ...defaultWslInstance,
      currentConfig: Effect.succeedSome(retryingConfig),
      snapshot: Effect.succeed({
        desiredRunning: true,
        ready: false,
        activePid: Option.none(),
        restartAttempt: 2,
        restartScheduled: true,
      }),
    };

    return Effect.gen(function* () {
      const result = yield* getLocalEnvironmentBootstraps.handler();
      assert.deepEqual(result, [
        {
          id: "wsl:default",
          label: "WSL (default distro)",
          runningDistro: null,
          httpBaseUrl: null,
          wsBaseUrl: null,
        },
      ]);
    }).pipe(Effect.provide(bootstrapsLayer([retryingInstance])));
  });

  it.effect("omits a bounded transient bootstrap after retries stop", () => {
    const stoppedInstance: DesktopBackendManager.DesktopBackendInstance = {
      ...defaultWslInstance,
      currentConfig: Effect.succeedSome({
        ...readyWslConfig,
        preflightFailure: Option.some({
          reason: "WSL probe timed out",
          fatal: false,
          retryLimit: 12,
        }),
      }),
      snapshot: Effect.succeed({
        desiredRunning: false,
        ready: false,
        activePid: Option.none(),
        restartAttempt: 12,
        restartScheduled: false,
      }),
    };

    return Effect.gen(function* () {
      const result = yield* getLocalEnvironmentBootstraps.handler();
      assert.deepEqual(result, []);
    }).pipe(Effect.provide(bootstrapsLayer([stoppedInstance])));
  });
});

describe("controlWindow", () => {
  it.effect(
    "minimizes, toggles maximize both ways, and closes through the normal close path",
    () => {
      let maximized = false;
      let minimized = false;
      let closed = false;
      const window = {
        isDestroyed: () => false,
        isFullScreen: () => false,
        isMaximized: () => maximized,
        minimize: () => {
          minimized = true;
        },
        maximize: () => {
          maximized = true;
        },
        unmaximize: () => {
          maximized = false;
        },
        close: () => {
          closed = true;
        },
      } as Electron.BrowserWindow;
      return Effect.gen(function* () {
        yield* controlWindow.handler("minimize");
        assert.isTrue(minimized);
        yield* controlWindow.handler("toggle-maximize");
        assert.isTrue(maximized);
        yield* controlWindow.handler("toggle-maximize");
        assert.isFalse(maximized);
        yield* controlWindow.handler("close");
        assert.isTrue(closed);
      }).pipe(
        Effect.provide(
          Layer.mock(ElectronWindow.ElectronWindow)({
            main: Effect.succeedSome(window),
          }),
        ),
      );
    },
  );

  it.effect("ignores a late action after the main window has closed", () =>
    controlWindow
      .handler("close")
      .pipe(
        Effect.provide(Layer.mock(ElectronWindow.ElectronWindow)({ main: Effect.succeedNone })),
      ),
  );

  it.effect("rejects actions outside the caption-button contract", () =>
    Effect.gen(function* () {
      const result = yield* Effect.exit(controlWindow.handler("destroy"));
      assert.equal(result._tag, "Failure");
    }).pipe(
      Effect.provide(Layer.mock(ElectronWindow.ElectronWindow)({ main: Effect.succeedNone })),
    ),
  );
});

