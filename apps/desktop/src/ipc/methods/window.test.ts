describe("pasteAsText", () => {
  it.effect(
    "pastes into the focused guest only after the main renderer acknowledges the menu action",
    () => {
      const paste = vi.fn();
      const mainPaste = vi.fn();
      const window = {
        webContents: { id: 42, paste: mainPaste },
        isDestroyed: () => false,
      } as unknown as Electron.BrowserWindow;
      focusedWebContents.mockReturnValue({ paste, isDestroyed: () => false });
      ownerWindow.mockReturnValue(window);

      return Effect.gen(function* () {
        yield* pasteAsText.handler(undefined, { sender: { id: 42 } });
        assert.equal(paste.mock.calls.length, 1);
        assert.equal(mainPaste.mock.calls.length, 0);

        yield* pasteAsText.handler(undefined, { sender: { id: 99 } });
        assert.equal(paste.mock.calls.length, 1);
        ownerWindow.mockReturnValue({}); // A focused PiP/other BrowserWindow.
        yield* pasteAsText.handler(undefined, { sender: { id: 42 } });
        assert.equal(paste.mock.calls.length, 1);
        ownerWindow.mockReturnValue(null); // Detached contents.
        yield* pasteAsText.handler(undefined, { sender: { id: 42 } });
        assert.equal(paste.mock.calls.length, 1);
        ownerWindow.mockReturnValue(window);
        focusedWebContents.mockReturnValue({ paste, isDestroyed: () => true });
        yield* pasteAsText.handler(undefined, { sender: { id: 42 } });
        assert.equal(paste.mock.calls.length, 1);
        focusedWebContents.mockReturnValue(null);
        yield* pasteAsText.handler(undefined, { sender: { id: 42 } });
        assert.equal(paste.mock.calls.length, 1);
      }).pipe(
        Effect.provide(
          Layer.mock(ElectronWindow.ElectronWindow)({
            main: Effect.succeedSome(window),
          }),
        ),
      );
    },
  );
});

describe("background image IPC", () => {
  /** Uses the real environment resolver with an isolated home instead of partial service values. */
  const backgroundEnvironment = (root: string) =>
    DesktopEnvironment.layer({
      dirname: root,
      homeDirectory: root,
      platform: "win32",
      processArch: "x64",
      appVersion: "1.0.0",
      appPath: root,
      isPackaged: false,
      resourcesPath: root,
      runningUnderArm64Translation: false,
    }).pipe(
      Layer.provide(
        Layer.mergeAll(NodeServices.layer, DesktopConfig.layerTest({ T3CODE_HOME: root })),
      ),
    );
  it.effect("selects, reads and clears the copied background", () =>
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem;
      const root = yield* fs.makeTempDirectoryScoped();
      yield* fs.writeFileString(`${root}/image.PNG`, "abc");
      yield* Effect.gen(function* () {
        assert.isNull(yield* getBackgroundImage.handler(undefined));
        assert.equal(
          yield* pickBackgroundImage.handler(undefined),
          "/__t3/background/ba7816bf8f01cfea.png",
        );
        yield* fs.remove(`${root}/image.PNG`);
        assert.equal(
          yield* getBackgroundImage.handler(undefined),
          "/__t3/background/ba7816bf8f01cfea.png",
        );
        assert.equal(
          yield* fs.readFileString(`${root}/userdata/background/ba7816bf8f01cfea.png`),
          "abc",
        );
        yield* clearBackgroundImage.handler(undefined);
        assert.isNull(yield* getBackgroundImage.handler(undefined));
        assert.deepEqual(yield* fs.readDirectory(`${root}/userdata/background`), []);
      }).pipe(
        Effect.provide(
          Layer.mergeAll(
            DesktopUiLocale.layerTest(),
            backgroundEnvironment(root),
            Layer.mock(ElectronDialog.ElectronDialog)({
              pickFiles: () => Effect.succeed([`${root}/image.PNG`]),
            }),
            Layer.mock(ElectronWindow.ElectronWindow)({ focusedMainOrFirst: Effect.succeedNone }),
          ),
        ),
      );
    }).pipe(Effect.provide(NodeServices.layer), Effect.scoped),
  );

  it.effect("returns null on cancellation and preserves the current background", () =>
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem;
      const root = yield* fs.makeTempDirectoryScoped();
      yield* fs.makeDirectory(`${root}/userdata/background`, { recursive: true });
      yield* fs.writeFileString(`${root}/userdata/background/ba7816bf8f01cfea.png`, "abc");
      yield* Effect.gen(function* () {
        assert.isNull(yield* pickBackgroundImage.handler(undefined));
        assert.equal(
          yield* getBackgroundImage.handler(undefined),
          "/__t3/background/ba7816bf8f01cfea.png",
        );
      }).pipe(
        Effect.provide(
          Layer.mergeAll(
            DesktopUiLocale.layerTest(),
            backgroundEnvironment(root),
            Layer.mock(ElectronDialog.ElectronDialog)({ pickFiles: () => Effect.succeed([]) }),
            Layer.mock(ElectronWindow.ElectronWindow)({ focusedMainOrFirst: Effect.succeedNone }),
          ),
        ),
      );
    }).pipe(Effect.provide(NodeServices.layer), Effect.scoped),
  );
});

describe("pickProjectFavicon", () => {
  const pickerLayer = (
    pickFiles: () => Effect.Effect<Array<string>>,
    settings?: DesktopAppSettings.DesktopSettings,
  ) =>
    Layer.mergeAll(
      DesktopUiLocale.layerTest(),
      Layer.mock(ElectronDialog.ElectronDialog)({ pickFiles }),
      Layer.mock(ElectronWindow.ElectronWindow)({
        focusedMainOrFirst: Effect.succeedNone,
      }),
      DesktopAppSettings.layerTest(settings),
    );

  it.effect("opens a single-image picker from the project directory", () =>
    Effect.gen(function* () {
      const pickFiles = vi.fn(() => Effect.succeed(["/pictures/icon.png"]));
      const result = yield* pickProjectFavicon
        .handler("/project")
        .pipe(Effect.provide(pickerLayer(pickFiles)));

      assert.strictEqual(result, "/pictures/icon.png");
      assert.deepEqual(pickFiles.mock.calls, [
        [
          {
            owner: Option.none(),
            defaultPath: Option.some("/project"),
            multiple: false,
            filters: [
              {
                name: "Images",
                extensions: ["avif", "gif", "ico", "jpeg", "jpg", "png", "svg", "webp", "icns"],
              },
            ],
          },
        ],
      ]);
    }),
  );

  it.effect("does not open a picker while the local environment is off", () =>
    Effect.gen(function* () {
      const pickFiles = vi.fn(() => Effect.succeed(["/pictures/icon.png"]));
      const result = yield* pickProjectFavicon.handler("/project").pipe(
        Effect.provide(
          pickerLayer(pickFiles, {
            ...DesktopAppSettings.DEFAULT_DESKTOP_SETTINGS,
            localEnvironmentEnabled: false,
          }),
        ),
      );
      assert.equal(result, null);
      assert.equal(pickFiles.mock.calls.length, 0);
    }),
  );
});

